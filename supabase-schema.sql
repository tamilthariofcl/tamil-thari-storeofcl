-- Tamil Thari store starter schema for Supabase (Postgres)
-- Run in Supabase SQL Editor only after creating a project.
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  price numeric(10,2) not null check (price >= 0),
  mrp numeric(10,2) not null check (mrp >= 0),
  offer_label text,
  image_url text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.customer_orders (
  id bigint generated by default as identity primary key,
  order_code text unique not null,
  customer_name text not null,
  phone text not null,
  email text,
  delivery_address text not null,
  items jsonb not null,
  total numeric(10,2) not null check (total >= 0),
  payment_screenshot_path text,
  payment_status text not null default 'pending_manual_verification',
  customer_note text,
  created_at timestamptz not null default now()
);
create table if not exists public.store_admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);
alter table public.products enable row level security;
alter table public.customer_orders enable row level security;
alter table public.store_admins enable row level security;
create or replace function public.is_store_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists(select 1 from public.store_admins where user_id = auth.uid()); $$;
create policy "Public can read active products" on public.products
for select using (active = true or public.is_store_admin());
create policy "Admins manage products" on public.products
for all using (public.is_store_admin()) with check (public.is_store_admin());
-- Orders should be created through a trusted server/Edge Function after validation.
-- Do NOT add a public select policy for customer_orders.
create policy "Admins read orders" on public.customer_orders
for select using (public.is_store_admin());
create policy "Admins update orders" on public.customer_orders
for update using (public.is_store_admin()) with check (public.is_store_admin());
